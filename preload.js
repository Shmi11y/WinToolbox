const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  onSystemTheme: (cb) => ipcRenderer.on('theme:system', (e, dark) => cb(dark)),
  onCloseAsk: (cb) => ipcRenderer.on('close:ask', () => cb()),
  closeAnswer: (opt) => ipcRenderer.invoke('close:answer', opt),
  settingsGet: () => ipcRenderer.invoke('settings:get'),
  settingsSet: (k, v) => ipcRenderer.invoke('settings:set', k, v),
  settingsOpenDir: (w) => ipcRenderer.invoke('settings:open-dir', w),
  setupCheck: () => ipcRenderer.invoke('setup:check'),
  setupScan: () => ipcRenderer.invoke('setup:scan'),
  openDownloads: () => ipcRenderer.invoke('setup:open-downloads'),
  setupPick: () => ipcRenderer.invoke('setup:pick'),
  setupSave: (dir) => ipcRenderer.invoke('setup:save', dir),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  catalog: () => ipcRenderer.invoke('catalog'),
  icons: (ids) => ipcRenderer.invoke('icons', ids),
  launch: (id) => ipcRenderer.invoke('launch', id),
  fav: (id) => ipcRenderer.invoke('fav', id),
  hardware: (force) => ipcRenderer.invoke('hardware', force),
  store: () => ipcRenderer.invoke('store'),
  theme: (t) => ipcRenderer.invoke('theme', t),
  reveal: (id) => ipcRenderer.invoke('reveal', id),
  openFolder: (w) => ipcRenderer.invoke('open-folder', w),
  stats: () => ipcRenderer.invoke('stats'),
  win: (a) => ipcRenderer.send('win', a),
  onWinState: (cb) => ipcRenderer.on('win-state', (e, v) => cb(v)),

  // 系统信息 / 调优
  sysinfo: (force) => ipcRenderer.invoke('sysinfo', !!force),
  tweaks: () => ipcRenderer.invoke('tweaks'),
  profileExport: () => ipcRenderer.invoke('profile:export'),
  profilePick: () => ipcRenderer.invoke('profile:pick'),
  profileApply: (doc, opts) => ipcRenderer.invoke('profile:apply', doc, opts),
  onProfileProgress: (cb) => ipcRenderer.on('profile:progress', (e, p) => cb(p)),
  pawnioStatus: () => ipcRenderer.invoke('sensors:pawnio'),
  pawnioInstall: () => ipcRenderer.invoke('sensors:pawnio-install'),
  onPawnioProgress: (cb) => ipcRenderer.on('pawnio:progress', (e, m) => cb(m)),
  tweakDetectBatch: (ids) => ipcRenderer.invoke('tweaks:detect-batch', ids),
  tweak: (id, action, value) => ipcRenderer.invoke('tweak', id, action, value),
  isAdmin: () => ipcRenderer.invoke('is-admin'),
  elevationLog: () => ipcRenderer.invoke('elevation-log'),
  relaunchAdmin: () => ipcRenderer.invoke('relaunch-admin'),

  // 自定义工具
  customPick: () => ipcRenderer.invoke('custom:pick'),
  customAdd: (items) => ipcRenderer.invoke('custom:add', items),
  customUpdate: (id, patch) => ipcRenderer.invoke('custom:update', id, patch),
  customRemove: (id) => ipcRenderer.invoke('custom:remove', id),
  customRelocate: (id) => ipcRenderer.invoke('custom:relocate', id),
  customExport: () => ipcRenderer.invoke('custom:export'),
  customImport: () => ipcRenderer.invoke('custom:import'),
  setSideW: (w) => ipcRenderer.invoke('ui:sidebar', w),
  sidebarOrder: (payload) => ipcRenderer.invoke('sidebar:order', payload),
  addCat: (name) => ipcRenderer.invoke('sidebar:addcat', name),
  pinCat: (id, on) => ipcRenderer.invoke('sidebar:pin', id, on),
  setCatSort: (id, mode) => ipcRenderer.invoke('sidebar:catsort', id, mode),
  renameCat: (id, name) => ipcRenderer.invoke('sidebar:renamecat', id, name),
  removeCat: (id) => ipcRenderer.invoke('sidebar:removecat', id),
  diagErrors: () => ipcRenderer.invoke('diag:errors'),
  diagClear: () => ipcRenderer.invoke('diag:clear'),
  logErr: (scope, msg) => ipcRenderer.invoke('log:err', scope, msg),
  pathForFile: (file) => { try { return webUtils.getPathForFile(file); } catch { return file.path || ''; } }
});
